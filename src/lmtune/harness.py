"""Client harness configs that use only the local server, with no telemetry or cloud paths.

OpenCode (v1 config schema, validated against opencode 1.19.4 with `opencode debug config` and
`opencode models`): a single local provider, sharing/auto-update off, web and shell tools ask
first. Its network-reaching features are additionally switched off by environment variables
in a wrapper, since they have no config keys in this version.

With a vision projector configured (`mmproj`), the model is declared image-capable so OpenCode
attaches images; with the media worker installed, its MCP tools (ffmpeg, exiftool, whisper.cpp;
no network, one folder) are added as a remote MCP server on loopback, its key read from its file.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from .config import ServeConfig
from .media import MediaConfig

PROVIDER = "lmtune"
MEDIA_MCP = "media"  # tool names become media_transcribe, media_probe, ...

# read by opencode 1.19.4 (found in the binary): no update checks, no models.dev catalog fetch,
# no on-demand language-server downloads, no skills fetched from URLs
OPENCODE_ENV = {
    "OPENCODE_DISABLE_AUTOUPDATE": "1",
    "OPENCODE_DISABLE_MODELS_FETCH": "1",
    "OPENCODE_DISABLE_LSP_DOWNLOAD": "1",
    "OPENCODE_DISABLE_EXTERNAL_SKILLS": "1",
}


def opencode_config(
    cfg: ServeConfig, *, output_tokens: int = 32768, media: MediaConfig | None = None
) -> dict[str, Any]:
    if cfg.api_key_file is None:
        raise ValueError("serve config has no api_key_file")
    model = f"{PROVIDER}/{cfg.alias}"
    model_cfg: dict[str, Any] = {
        "name": f"{cfg.alias} (local)",
        "limit": {"context": cfg.ctx, "output": min(output_tokens, cfg.ctx // 2)},
    }
    if cfg.mmproj is not None:
        model_cfg |= {"attachment": True, "modalities": {"input": ["text", "image"], "output": ["text"]}}
    out: dict[str, Any] = {
        "$schema": "https://opencode.ai/config.json",
        "provider": {
            PROVIDER: {
                "npm": "@ai-sdk/openai-compatible",
                "name": "Local (lmtune)",
                "options": {
                    "baseURL": f"{cfg.url}/v1",
                    # read from the 0600 key file at startup; never stored in this config
                    "apiKey": f"{{file:{cfg.api_key_file}}}",
                },
                "models": {cfg.alias: model_cfg},
            }
        },
        "model": model,
        "small_model": model,
        "enabled_providers": [PROVIDER],
        "share": "disabled",
        "autoupdate": False,
        "permission": {"bash": "ask", "webfetch": "ask", "edit": "allow"},
    }
    if media is not None:
        out["mcp"] = {
            MEDIA_MCP: {
                "type": "remote",
                "url": f"http://127.0.0.1:{media.port}/mcp",
                "enabled": True,
                # read from the 0600 key file at startup; never stored in this config
                "headers": {"Authorization": f"Bearer {{file:{media.key_file}}}"},
                "oauth": False,  # a bearer key, not OAuth: don't probe for an authorization server
                "timeout": media.timeout_s * 1000,  # default 5 s; transcribing an hour takes minutes
            }
        }
    return out


def wrapper_script(opencode_bin: str) -> str:
    exports = "\n".join(f"export {k}={v}" for k, v in OPENCODE_ENV.items())
    return (
        "#!/bin/sh\n"
        "# opencode against the local lmtune server, with its network-reaching extras switched off.\n"
        "# Generated by `lmtune harness opencode --write`.\n"
        f"{exports}\n"
        "unset OPENCODE_AUTO_SHARE\n"
        f'exec {opencode_bin} "$@"\n'
    )


def write_opencode(
    cfg: ServeConfig, config_path: Path, wrapper_path: Path, *, media: MediaConfig | None = None
) -> list[Path]:
    """Write config (backing up any existing file) and the wrapper. Returns written paths."""
    written = []
    config_path.parent.mkdir(parents=True, exist_ok=True)
    if config_path.exists():
        backup = config_path.with_suffix(config_path.suffix + ".bak")
        shutil.copy2(config_path, backup)
        written.append(backup)
    config_path.write_text(json.dumps(opencode_config(cfg, media=media), indent=2) + "\n")
    written.append(config_path)
    exe = shutil.which("opencode") or "/opt/homebrew/bin/opencode"
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)
    wrapper_path.write_text(wrapper_script(exe))
    wrapper_path.chmod(0o755)
    written.append(wrapper_path)
    return written
